CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key      INTEGER     PRIMARY KEY,          
    full_date     DATE        NOT NULL UNIQUE,
    day_of_month  SMALLINT    NOT NULL,
    month_num     SMALLINT    NOT NULL,
    month_name    VARCHAR(12) NOT NULL,
    quarter_num   SMALLINT    NOT NULL,
    year_num      SMALLINT    NOT NULL,
    day_of_week   SMALLINT    NOT NULL,            
    day_name      VARCHAR(12) NOT NULL,
    week_of_year  SMALLINT    NOT NULL,
    is_weekend    BOOLEAN     NOT NULL
);

INSERT INTO dwh.dim_date
SELECT to_char(d, 'YYYYMMDD')::int,
       d::date,
       extract(day     FROM d)::smallint,
       extract(month   FROM d)::smallint,
       trim(to_char(d, 'Month')),
       extract(quarter FROM d)::smallint,
       extract(year    FROM d)::smallint,
       extract(isodow  FROM d)::smallint,
       trim(to_char(d, 'Day')),
       extract(week    FROM d)::smallint,
       extract(isodow  FROM d) IN (5, 6)            
FROM generate_series('2024-01-01'::date, '2030-12-31'::date, interval '1 day') AS g(d)
ON CONFLICT (date_key) DO NOTHING;


CREATE TABLE IF NOT EXISTS dwh.dim_patient (
    patient_key     BIGSERIAL   PRIMARY KEY,         
    patient_id      VARCHAR(20) NOT NULL,           
    full_name       VARCHAR(120) NOT NULL,
    gender          CHAR(1)     NOT NULL,
    date_of_birth   DATE        NOT NULL,
    city            VARCHAR(60),
    insurance_type  VARCHAR(30) NOT NULL,
    registered_date DATE        NOT NULL,
    row_hash        CHAR(32)    NOT NULL,          
    valid_from      DATE        NOT NULL,
    valid_to        DATE        NOT NULL DEFAULT '9999-12-31',
    is_current      BOOLEAN     NOT NULL DEFAULT TRUE,
    UNIQUE (patient_id, valid_from)
);
CREATE INDEX IF NOT EXISTS ix_dim_patient_current
    ON dwh.dim_patient (patient_id) WHERE is_current;
CREATE INDEX IF NOT EXISTS ix_dim_patient_asof
    ON dwh.dim_patient (patient_id, valid_from, valid_to);

CREATE TABLE IF NOT EXISTS dwh.dim_doctor (
    doctor_key  BIGSERIAL    PRIMARY KEY,
    doctor_id   VARCHAR(20)  NOT NULL UNIQUE,
    full_name   VARCHAR(120) NOT NULL,
    department  VARCHAR(60)  NOT NULL,
    specialty   VARCHAR(80),
    hire_date   DATE,
    is_active   BOOLEAN      NOT NULL,
    batch_date  DATE         NOT NULL,       
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dwh.dim_test (
    test_key   BIGSERIAL    PRIMARY KEY,
    test_code  VARCHAR(20)  NOT NULL UNIQUE,
    test_name  VARCHAR(80)  NOT NULL,
    category   VARCHAR(40)  NOT NULL,
    unit       VARCHAR(20),
    ref_low    NUMERIC(12,3),
    ref_high   NUMERIC(12,3),
    list_price NUMERIC(10,2)
);

CREATE TABLE IF NOT EXISTS dwh.dim_diagnosis (
    diagnosis_key  INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnosis_code VARCHAR(12)  NOT NULL UNIQUE,
    description    VARCHAR(160) NOT NULL,
    category       VARCHAR(60)  NOT NULL
);
INSERT INTO dwh.dim_diagnosis (diagnosis_key, diagnosis_code, description, category)
VALUES (-1, 'UNK', 'Unknown / not recorded', 'Unknown')
ON CONFLICT (diagnosis_key) DO NOTHING;


CREATE TABLE IF NOT EXISTS dwh.fact_visits (
    visit_key        BIGSERIAL     PRIMARY KEY,
    visit_id         VARCHAR(30)   NOT NULL UNIQUE,   -- natural key -> idempotent upserts
    date_key         INTEGER       NOT NULL REFERENCES dwh.dim_date (date_key),
    patient_key      BIGINT        NOT NULL REFERENCES dwh.dim_patient (patient_key),
    doctor_key       BIGINT        NOT NULL REFERENCES dwh.dim_doctor (doctor_key),
    diagnosis_key    INTEGER       NOT NULL REFERENCES dwh.dim_diagnosis (diagnosis_key),
    visit_ts         TIMESTAMP     NOT NULL,
    visit_type       VARCHAR(20)   NOT NULL,          -- degenerate dimension
    status           VARCHAR(15)   NOT NULL,          -- degenerate dimension
    consultation_fee NUMERIC(10,2) NOT NULL,
    discount         NUMERIC(10,2) NOT NULL,
    net_amount       NUMERIC(10,2) NOT NULL,
    batch_date       DATE          NOT NULL,
    loaded_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fact_visits_date    ON dwh.fact_visits (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_visits_patient ON dwh.fact_visits (patient_key);
CREATE INDEX IF NOT EXISTS ix_fact_visits_doctor  ON dwh.fact_visits (doctor_key);

CREATE TABLE IF NOT EXISTS dwh.fact_lab_tests (
    lab_key             BIGSERIAL     PRIMARY KEY,
    lab_order_id        VARCHAR(30)   NOT NULL UNIQUE,
    visit_key           BIGINT        NOT NULL REFERENCES dwh.fact_visits (visit_key),
    date_key            INTEGER       NOT NULL REFERENCES dwh.dim_date (date_key),
    patient_key         BIGINT        NOT NULL REFERENCES dwh.dim_patient (patient_key),
    doctor_key          BIGINT        NOT NULL REFERENCES dwh.dim_doctor (doctor_key),
    test_key            BIGINT        NOT NULL REFERENCES dwh.dim_test (test_key),
    ordered_at          TIMESTAMP     NOT NULL,
    resulted_at         TIMESTAMP,
    turnaround_minutes  INTEGER,                      -- NULL while the result is pending
    result_value        NUMERIC(12,3),
    result_flag         VARCHAR(10)   NOT NULL,       -- Normal / High / Low / Pending
    test_price          NUMERIC(10,2) NOT NULL,
    batch_date          DATE          NOT NULL,
    loaded_at           TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fact_lab_date  ON dwh.fact_lab_tests (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_lab_test  ON dwh.fact_lab_tests (test_key);
CREATE INDEX IF NOT EXISTS ix_fact_lab_visit ON dwh.fact_lab_tests (visit_key);
